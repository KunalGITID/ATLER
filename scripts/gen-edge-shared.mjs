// Copies src/lib/dates.js + src/lib/reminders.js into the send-reminders Edge
// Function as one file, so the server computes renewals exactly like the app.
// Run after changing either file:  node scripts/gen-edge-shared.mjs
// test/edge-shared.test.js fails if the copy is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
export const OUTPUT = new URL('supabase/functions/send-reminders/shared.generated.js', root);

export function buildShared() {
    const read = path => readFileSync(new URL(path, root), 'utf8');
    const reminders = read('src/lib/reminders.js').replace(/^import .*\n/gm, '');
    return [
        '// GENERATED by scripts/gen-edge-shared.mjs from src/lib/dates.js and',
        '// src/lib/reminders.js. Do not edit by hand.',
        '',
        read('src/lib/dates.js'),
        reminders,
    ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    writeFileSync(OUTPUT, buildShared());
    console.log(`wrote ${fileURLToPath(OUTPUT)}`);
}
